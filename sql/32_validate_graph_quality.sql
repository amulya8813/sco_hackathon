USE SCHEMA SCO_HACKATHON.SCO_GOVERNANCE;

-- G01: No orphan source edges
INSERT INTO DQ_CHECK_RESULT (CHECK_NAME, QUALITY_DIMENSION, LAYER_NAME, OBJECT_NAME,
    OBSERVED_VALUE, EXPECTED_CONDITION, PASSED_FLAG, SEVERITY, SOURCE_OBJECT, ALERT_ELIGIBLE_FLAG)
SELECT 'No orphan source edges', 'GRAPH', 'GRAPH', 'V_ALL_EDGES',
    (SELECT COUNT(*) FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_EDGES e
     LEFT JOIN SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES n ON n.NODE_ID = e.SOURCE_NODE_ID
     WHERE n.NODE_ID IS NULL AND e.DIRECTION <> 'SELF'),
    'orphan_count = 0',
    (SELECT COUNT(*) FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_EDGES e
     LEFT JOIN SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES n ON n.NODE_ID = e.SOURCE_NODE_ID
     WHERE n.NODE_ID IS NULL AND e.DIRECTION <> 'SELF') = 0,
    'HIGH', 'SCO_GRAPH', TRUE;

-- G02: No orphan target edges
INSERT INTO DQ_CHECK_RESULT (CHECK_NAME, QUALITY_DIMENSION, LAYER_NAME, OBJECT_NAME,
    OBSERVED_VALUE, EXPECTED_CONDITION, PASSED_FLAG, SEVERITY, SOURCE_OBJECT, ALERT_ELIGIBLE_FLAG)
SELECT 'No orphan target edges', 'GRAPH', 'GRAPH', 'V_ALL_EDGES',
    (SELECT COUNT(*) FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_EDGES e
     LEFT JOIN SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES n ON n.NODE_ID = e.TARGET_NODE_ID
     WHERE n.NODE_ID IS NULL AND e.DIRECTION <> 'SELF'),
    'orphan_count = 0',
    (SELECT COUNT(*) FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_EDGES e
     LEFT JOIN SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES n ON n.NODE_ID = e.TARGET_NODE_ID
     WHERE n.NODE_ID IS NULL AND e.DIRECTION <> 'SELF') = 0,
    'HIGH', 'SCO_GRAPH', TRUE;

-- G03: All 13 node types valid
INSERT INTO DQ_CHECK_RESULT (CHECK_NAME, QUALITY_DIMENSION, LAYER_NAME, OBJECT_NAME,
    OBSERVED_VALUE, EXPECTED_CONDITION, PASSED_FLAG, SEVERITY, SOURCE_OBJECT, ALERT_ELIGIBLE_FLAG)
SELECT 'All node types valid (13)', 'GRAPH', 'GRAPH', 'V_ALL_NODES',
    COUNT(DISTINCT NODE_TYPE), '13 approved types',
    COUNT(DISTINCT NODE_TYPE) = 13, 'MEDIUM', 'SCO_GRAPH', FALSE
FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES;

-- G04: Polymorphic resolution complete
INSERT INTO DQ_CHECK_RESULT (CHECK_NAME, QUALITY_DIMENSION, LAYER_NAME, OBJECT_NAME,
    OBSERVED_VALUE, EXPECTED_CONDITION, PASSED_FLAG, SEVERITY, SOURCE_OBJECT, ALERT_ELIGIBLE_FLAG)
SELECT 'Polymorphic shipment origin resolved', 'GRAPH', 'GRAPH', 'V_EDGE_SHIPMENT_ORIGINATES_FROM',
    COUNT_IF(TARGET_NODE_ID = 'UNKNOWN'), 'No UNKNOWN targets',
    COUNT_IF(TARGET_NODE_ID = 'UNKNOWN') = 0, 'HIGH', 'SCO_GRAPH', TRUE
FROM SCO_HACKATHON.SCO_GRAPH.V_EDGE_SHIPMENT_ORIGINATES_FROM;

-- G05: Node ID format valid
INSERT INTO DQ_CHECK_RESULT (CHECK_NAME, QUALITY_DIMENSION, LAYER_NAME, OBJECT_NAME,
    OBSERVED_VALUE, EXPECTED_CONDITION, PASSED_FLAG, SEVERITY, SOURCE_OBJECT, ALERT_ELIGIBLE_FLAG)
SELECT 'Node ID format TYPE:id', 'GRAPH', 'GRAPH', 'V_ALL_NODES',
    COUNT_IF(NODE_ID NOT LIKE NODE_TYPE || ':%'), 'All match TYPE:id',
    COUNT_IF(NODE_ID NOT LIKE NODE_TYPE || ':%') = 0, 'MEDIUM', 'SCO_GRAPH', FALSE
FROM SCO_HACKATHON.SCO_GRAPH.V_ALL_NODES;

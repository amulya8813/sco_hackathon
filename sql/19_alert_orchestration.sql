USE SCHEMA SCO_HACKATHON.SCO_MONITORING;

CREATE OR REPLACE PROCEDURE SP_RUN_ALERT_DETECTION()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
COMMENT = 'Runs the full alert detection cycle: business alerts, DQ alerts, deduplication, auto-resolution'
AS
BEGIN
    -- Step 1: Detect business alerts
    -- B1: OTD
    INSERT INTO ALERT_EVENT (ALERT_TYPE, ALERT_CATEGORY, SEVERITY, ENTITY_TYPE, ENTITY_ID,
        METRIC_NAME, OBSERVED_VALUE, THRESHOLD_VALUE, ALERT_MESSAGE, SOURCE_OBJECT, DEDUP_KEY)
    SELECT 'OTD_BELOW_THRESHOLD', 'BUSINESS', 'CRITICAL', 'SUPPLIER', SUPPLIER_NAME,
        'OTD_RATE', ROUND(SUM(LINES_ON_TIME)/NULLIF(SUM(LINES_DUE),0)*100, 2), 95.0,
        'OTD for ' || SUPPLIER_NAME || ': ' || ROUND(SUM(LINES_ON_TIME)/NULLIF(SUM(LINES_DUE),0)*100,2) || '% (threshold: 95%)',
        'SCO_GOLD.GLD_METRIC_OTD', 'OTD_BELOW:' || SUPPLIER_NAME || ':' || DATE_TRUNC('month', CURRENT_DATE())
    FROM SCO_HACKATHON.SCO_GOLD.GLD_METRIC_OTD
    WHERE MONTH_START_DATE >= DATEADD('month', -3, CURRENT_DATE())
    GROUP BY SUPPLIER_NAME
    HAVING SUM(LINES_ON_TIME)/NULLIF(SUM(LINES_DUE),0)*100 < 95
       AND NOT EXISTS (SELECT 1 FROM ALERT_EVENT ae
           WHERE ae.DEDUP_KEY = 'OTD_BELOW:' || SUPPLIER_NAME || ':' || DATE_TRUNC('month', CURRENT_DATE())
             AND ae.STATUS = 'OPEN');

    -- B5: Stockouts
    INSERT INTO ALERT_EVENT (ALERT_TYPE, ALERT_CATEGORY, SEVERITY, ENTITY_TYPE, ENTITY_ID,
        METRIC_NAME, OBSERVED_VALUE, THRESHOLD_VALUE, ALERT_MESSAGE, SOURCE_OBJECT, DEDUP_KEY)
    SELECT 'INVENTORY_SHORTAGE', 'BUSINESS', 'CRITICAL', 'PART', PART_NAME,
        'STOCKOUT_FLAG', 0, 0,
        'Stockout: ' || PART_NAME || ' at ' || WAREHOUSE_NAME,
        'SCO_GOLD.GLD_INVENTORY_HEALTH', 'STOCKOUT:' || PART_ID || ':' || WAREHOUSE_ID
    FROM SCO_HACKATHON.SCO_GOLD.GLD_INVENTORY_HEALTH
    WHERE STOCKOUT_FLAG = TRUE
      AND NOT EXISTS (SELECT 1 FROM ALERT_EVENT ae
          WHERE ae.DEDUP_KEY = 'STOCKOUT:' || PART_ID || ':' || WAREHOUSE_ID AND ae.STATUS = 'OPEN');

    -- B6: Shipment delay risk
    INSERT INTO ALERT_EVENT (ALERT_TYPE, ALERT_CATEGORY, SEVERITY, ENTITY_TYPE, ENTITY_ID,
        METRIC_NAME, OBSERVED_VALUE, THRESHOLD_VALUE, ALERT_MESSAGE, SOURCE_OBJECT, DEDUP_KEY)
    SELECT 'SHIPMENT_DELAY_RISK', 'BUSINESS', 'HIGH', 'CARRIER', CARRIER_NAME,
        'ON_TIME_ARR_PCT', ON_TIME_ARRIVAL_RATE_PCT, 50.0,
        'Carrier ' || CARRIER_NAME || ' on ' || ROUTE_NAME || ': ' || ON_TIME_ARRIVAL_RATE_PCT || '% on-time',
        'SCO_GOLD.GLD_SHIPMENT_PERFORMANCE',
        'DELAY:' || CARRIER_ID || ':' || ROUTE_ID || ':' || MONTH_START_DATE
    FROM SCO_HACKATHON.SCO_GOLD.GLD_SHIPMENT_PERFORMANCE
    WHERE ON_TIME_ARRIVAL_RATE_PCT < 50 AND MONTH_START_DATE >= DATEADD('month', -3, CURRENT_DATE())
      AND NOT EXISTS (SELECT 1 FROM ALERT_EVENT ae
          WHERE ae.DEDUP_KEY = 'DELAY:' || CARRIER_ID || ':' || ROUTE_ID || ':' || MONTH_START_DATE
            AND ae.STATUS = 'OPEN');

    -- Step 2: Detect DQ alerts
    INSERT INTO ALERT_EVENT (ALERT_TYPE, ALERT_CATEGORY, SEVERITY, ENTITY_TYPE, ENTITY_ID,
        METRIC_NAME, OBSERVED_VALUE, THRESHOLD_VALUE, ALERT_MESSAGE, SOURCE_OBJECT, DEDUP_KEY)
    SELECT 'DQ_CHECK_FAILURE', 'DATA_QUALITY', 'HIGH', 'TABLE', DQ_DIMENSION || '.' || CHECK_NAME,
        CHECK_NAME, VIOLATION_COUNT, 0,
        'DQ check ' || CHECK_NAME || ' FAILED: ' || VIOLATION_COUNT || ' violations',
        'SCO_GOVERNANCE.V_DQ_SCORECARD', 'DQ_FAIL:' || DQ_DIMENSION || ':' || CHECK_NAME
    FROM SCO_HACKATHON.SCO_GOVERNANCE.V_DQ_SCORECARD
    WHERE STATUS = 'FAIL'
      AND NOT EXISTS (SELECT 1 FROM ALERT_EVENT ae
          WHERE ae.DEDUP_KEY = 'DQ_FAIL:' || DQ_DIMENSION || ':' || CHECK_NAME AND ae.STATUS = 'OPEN');

    -- Step 3: Auto-resolve recovered conditions
    UPDATE ALERT_EVENT SET STATUS = 'RESOLVED', RESOLVED_AT = CURRENT_TIMESTAMP(), UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE ALERT_TYPE = 'INVENTORY_SHORTAGE' AND STATUS = 'OPEN'
      AND NOT EXISTS (SELECT 1 FROM SCO_HACKATHON.SCO_GOLD.GLD_INVENTORY_HEALTH ih
          WHERE ih.STOCKOUT_FLAG = TRUE AND DEDUP_KEY = 'STOCKOUT:' || ih.PART_ID || ':' || ih.WAREHOUSE_ID);

    UPDATE ALERT_EVENT SET STATUS = 'RESOLVED', RESOLVED_AT = CURRENT_TIMESTAMP(), UPDATED_AT = CURRENT_TIMESTAMP()
    WHERE ALERT_TYPE = 'DQ_CHECK_FAILURE' AND STATUS = 'OPEN'
      AND NOT EXISTS (SELECT 1 FROM SCO_HACKATHON.SCO_GOVERNANCE.V_DQ_SCORECARD dq
          WHERE dq.STATUS = 'FAIL' AND DEDUP_KEY = 'DQ_FAIL:' || dq.DQ_DIMENSION || ':' || dq.CHECK_NAME);

    RETURN 'Alert detection cycle complete at ' || CURRENT_TIMESTAMP()::VARCHAR;
END;

-- ═══════════════════════════════════════════════════════════════════════
-- Scheduled task (initially suspended — resume when ready)
-- ═══════════════════════════════════════════════════════════════════════
CREATE OR REPLACE TASK TSK_ALERT_DETECTION
    USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
    SCHEDULE = 'USING CRON 0 * * * * UTC'
    COMMENT = 'Hourly alert detection cycle for business and DQ exceptions'
AS
    CALL SP_RUN_ALERT_DETECTION();


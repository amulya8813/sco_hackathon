
SHOW USERS;
GRANT ROLE STREAMLIT_VIEWER TO USER MSARSWAT;


USE ROLE ACCOUNTADMIN;
CREATE ROLE IF NOT EXISTS STREAMLIT_VIEWER;
SHOW STREAMLITS;

GRANT USAGE ON WAREHOUSE COMPUTE_WH                          TO ROLE STREAMLIT_VIEWER;
GRANT USAGE ON DATABASE  SCO_HACKATHON                       TO ROLE STREAMLIT_VIEWER;
GRANT USAGE ON SCHEMA    SCO_HACKATHON.SCO_GOLD              TO ROLE STREAMLIT_VIEWER;
GRANT USAGE ON STREAMLIT SCO_HACKATHON.SCO_GOLD.STREAMLIT   TO ROLE STREAMLIT_VIEWER;
GRANT SELECT ON ALL TABLES IN SCHEMA SCO_HACKATHON.SCO_GOLD TO ROLE STREAMLIT_VIEWER;
GRANT SELECT ON ALL VIEWS  IN SCHEMA SCO_HACKATHON.SCO_GOLD TO ROLE STREAMLIT_VIEWER;

GRANT ROLE STREAMLIT_VIEWER TO USER EVALUATOR;
ALTER USER EVALUATOR SET DEFAULT_ROLE = STREAMLIT_VIEWER;
ALTER USER EVALUATOR SET DEFAULT_WAREHOUSE = COMPUTE_WH;

GRANT USAGE ON ALL SCHEMAS IN DATABASE SCO_HACKATHON TO ROLE STREAMLIT_VIEWER;
GRANT SELECT ON ALL TABLES IN DATABASE SCO_HACKATHON TO ROLE STREAMLIT_VIEWER;
GRANT SELECT ON ALL VIEWS  IN DATABASE SCO_HACKATHON TO ROLE STREAMLIT_VIEWER;


SHOW GRANTS TO ROLE STREAMLIT_VIEWER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE STREAMLIT_VIEWER;
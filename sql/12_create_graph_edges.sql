CREATE OR REPLACE VIEW V_EDGE_ENTITY_HAS_ESG_SCORE AS
SELECT 'SUPPLIER:' || SUPPLIER_ID AS SOURCE_NODE_ID, 'SUPPLIER:' || SUPPLIER_ID AS TARGET_NODE_ID,
    'SUPPLIER' AS SOURCE_TYPE, 'SUPPLIER' AS TARGET_TYPE, 'ENTITY_HAS_ESG_SCORE' AS EDGE_TYPE,
    'SELF' AS DIRECTION, '1:N' AS CARDINALITY, 'Supplier has ESG score' AS BUSINESS_MEANING,
    'SCO_SILVER.SLV_FACT_ESG' AS SOURCE_TABLE, SUPPLIER_ID || ':ESG:' || ESG_SCORE_ID AS JOIN_KEY,
    OVERALL_ESG_SCORE, ENVIRONMENTAL_SCORE, SOCIAL_SCORE, GOVERNANCE_SCORE,
    SCORING_PERIOD, FORCED_LABOR_RISK, CONTROVERSY_FLAG

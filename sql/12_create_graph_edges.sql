SELECT 'PLANT:' || PLANT_ID, 'PLANT:' || PLANT_ID,
    'PLANT', 'PLANT', 'ENTITY_HAS_ESG_SCORE', 'SELF', '1:N', 'Plant has ESG score',
    'SCO_SILVER.SLV_FACT_ESG', PLANT_ID || ':ESG:' || ESG_SCORE_ID,
    OVERALL_ESG_SCORE, ENVIRONMENTAL_SCORE, SOCIAL_SCORE, GOVERNANCE_SCORE,

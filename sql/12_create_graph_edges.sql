CREATE OR REPLACE VIEW V_EDGE_PORT_LOCATED_IN_COUNTRY AS
WITH all_ports AS (
    SELECT DISTINCT ORIGIN_PORT_ID AS PORT_ID, ORIGIN_COUNTRY_ID AS COUNTRY_ID
    FROM SCO_HACKATHON.SCO_SILVER.SLV_DIM_ROUTE WHERE ORIGIN_PORT_ID IS NOT NULL AND ORIGIN_COUNTRY_ID IS NOT NULL
    UNION
    SELECT DISTINCT DESTINATION_PORT_ID, DESTINATION_COUNTRY_ID
    FROM SCO_HACKATHON.SCO_SILVER.SLV_DIM_ROUTE WHERE DESTINATION_PORT_ID IS NOT NULL AND DESTINATION_COUNTRY_ID IS NOT NULL
)
SELECT 'PORT:' || PORT_ID AS SOURCE_NODE_ID, 'COUNTRY:' || COUNTRY_ID AS TARGET_NODE_ID,
    'PORT' AS SOURCE_TYPE, 'COUNTRY' AS TARGET_TYPE, 'PORT_LOCATED_IN_COUNTRY' AS EDGE_TYPE,
    'OUTBOUND' AS DIRECTION, 'N:1' AS CARDINALITY, 'Port located in country' AS BUSINESS_MEANING,
    'SCO_SILVER.SLV_DIM_ROUTE (derived)' AS SOURCE_TABLE, PORT_ID || ':' || COUNTRY_ID AS JOIN_KEY
FROM all_ports;


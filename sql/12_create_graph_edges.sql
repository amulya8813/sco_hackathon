    'SCO_SILVER.SLV_FACT_SHIPMENT' AS SOURCE_TABLE,
    SHIPMENT_ID || ':' || COALESCE(ORIGIN_TYPE,'?') || ':' || COALESCE(ORIGIN_SUPPLIER_ID, ORIGIN_PLANT_ID, ORIGIN_WAREHOUSE_ID) AS JOIN_KEY

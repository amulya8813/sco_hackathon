"""
Jira Alert Handler — Dry-run / Live MCP sync for SCO supply-chain alerts.

Reads pending alerts from SCO_MONITORING.V_JIRA_SYNC_QUEUE,
builds Jira ticket payloads, and either logs them (dry-run) or
sends them via MCP (live mode).

Usage:
  - As a CoCo automation: cortex automation create ...
  - Manually: python scripts/jira_alert_handler.py [--live]

Environment:
  - Requires Snowflake session (via get_active_session or connection)
  - Requires Jira MCP configured: cortex mcp add jira
  - Config: config/jira_mcp_config.example.yaml
"""

import json
import os
from datetime import datetime


# ── Configuration ──────────────────────────────────────────────────────
DRY_RUN = os.getenv("JIRA_DRY_RUN", "true").lower() == "true"
PROJECT_KEY = os.getenv("JIRA_PROJECT_KEY", "PLACEHOLDER")
MAX_ALERTS_PER_RUN = int(os.getenv("JIRA_MAX_ALERTS", "50"))
MIN_SEVERITY = os.getenv("JIRA_MIN_SEVERITY", "MEDIUM")
DASHBOARD_URL = os.getenv("STREAMLIT_DASHBOARD_URL", "https://app.snowflake.com")

SEVERITY_ORDER = {"CRITICAL": 1, "HIGH": 2, "MEDIUM": 3, "LOW": 4}
PRIORITY_MAP = {"CRITICAL": "Highest", "HIGH": "High", "MEDIUM": "Medium", "LOW": "Low"}
LABELS = ["sco-hackathon", "coco-generated", "supply-chain"]


def get_session():
    """Get Snowflake session — works in Snowsight notebooks/Streamlit or locally."""
    try:
        from snowflake.snowpark.context import get_active_session
        return get_active_session()
    except Exception:
        import snowflake.connector
        conn = snowflake.connector.connect(connection_name="default")
        return conn.cursor()


def fetch_pending_alerts(session):
    """Fetch alerts pending Jira sync, filtered by severity."""
    min_sev = SEVERITY_ORDER.get(MIN_SEVERITY, 3)
    rows = session.sql(f"""
        SELECT * FROM SCO_HACKATHON.SCO_MONITORING.V_JIRA_SYNC_QUEUE
        LIMIT {MAX_ALERTS_PER_RUN}
    """).collect()
    # Filter by severity
    return [r for r in rows if SEVERITY_ORDER.get(r["SEVERITY"], 4) <= min_sev]


def build_jira_payload(alert):
    """Build a sanitized Jira issue payload — no credentials, no row-level data."""
    summary = f"[SCO-{alert['SEVERITY']}] {alert['ALERT_TYPE']}: {alert['ENTITY_ID'] or 'N/A'}"
    if len(summary) > 255:
        summary = summary[:252] + "..."

    description = f"""h2. Supply Chain Alert — {alert['ALERT_TYPE']}

*Category:* {alert['ALERT_CATEGORY']}
*Severity:* {alert['SEVERITY']}
*Affected Entity:* {alert['ENTITY_TYPE'] or 'N/A'} — {alert['ENTITY_ID'] or 'N/A'}
*Metric:* {alert['METRIC_NAME'] or 'N/A'}
*Observed Value:* {alert['OBSERVED_VALUE']}
*Governed Threshold:* {alert['THRESHOLD_VALUE']}
*Detected At:* {alert['DETECTED_AT']}
*Source Object:* {alert['SOURCE_OBJECT'] or 'N/A'}

h3. Alert Message
{alert['ALERT_MESSAGE']}

h3. Investigation Steps
# Open the SCO Supply Chain Analytics dashboard: [{DASHBOARD_URL}]
# Navigate to the relevant page (Executive Overview, Alerts & Data Quality, or Knowledge Graph)
# Review the metric trend and affected entities
# Check the governed threshold in GLD_METRIC_DEFINITIONS
# Assess downstream impact using the Knowledge Graph Explorer

h3. Metadata
* Alert ID: {alert['ALERT_ID']}
* Dedup Key: {{noformat}}{alert['DEDUP_KEY']}{{noformat}}
* Generated by: CoCo (Snowflake Cortex Code) — SCO Hackathon 2026
"""

    return {
        "project": {"key": PROJECT_KEY},
        "summary": summary,
        "description": description,
        "issuetype": {"name": "Bug" if alert["ALERT_CATEGORY"] == "DATA_QUALITY" else "Task"},
        "priority": {"name": PRIORITY_MAP.get(alert["SEVERITY"], "Medium")},
        "labels": LABELS + [alert["SEVERITY"].lower(), alert["ALERT_CATEGORY"].lower()],
    }


def log_sync(session, alert_id, action, payload, response_status, response_code,
             response_msg, jira_key, dry_run):
    """Log the sync attempt to JIRA_SYNC_LOG."""
    sanitized = json.dumps(payload) if payload else "NULL"
    session.sql(f"""
        INSERT INTO SCO_HACKATHON.SCO_MONITORING.JIRA_SYNC_LOG
            (ALERT_ID, SYNC_ACTION, REQUEST_PAYLOAD, RESPONSE_STATUS,
             RESPONSE_CODE, RESPONSE_MESSAGE, JIRA_ISSUE_KEY, DRY_RUN)
        SELECT {alert_id}, '{action}',
            PARSE_JSON($${sanitized}$$),
            '{response_status}', {response_code or 'NULL'},
            $${response_msg or ''}$$,
            {f"'{jira_key}'" if jira_key else 'NULL'},
            {dry_run}
    """).collect()


def update_alert_jira_status(session, alert_id, status, issue_key=None,
                              issue_url=None, error_msg=None):
    """Update the alert's Jira sync status."""
    parts = [f"JIRA_SYNC_STATUS = '{status}'", "JIRA_LAST_SYNC_AT = CURRENT_TIMESTAMP()",
             "UPDATED_AT = CURRENT_TIMESTAMP()"]
    if issue_key:
        parts.append(f"JIRA_ISSUE_KEY = '{issue_key}'")
    if issue_url:
        parts.append(f"JIRA_ISSUE_URL = '{issue_url}'")
    if error_msg:
        safe_msg = error_msg.replace("'", "''")[:4000]
        parts.append(f"JIRA_ERROR_MESSAGE = '{safe_msg}'")
    session.sql(f"""
        UPDATE SCO_HACKATHON.SCO_MONITORING.ALERT_EVENT
        SET {', '.join(parts)} WHERE ALERT_ID = {alert_id}
    """).collect()


def sync_alert_to_jira(session, alert, payload):
    """Sync a single alert — dry-run logs only, live calls MCP."""
    alert_id = alert["ALERT_ID"]

    if DRY_RUN:
        print(f"[DRY-RUN] Alert {alert_id}: {payload['summary']}")
        print(f"  Payload: {json.dumps(payload, indent=2)[:500]}")
        log_sync(session, alert_id, "CREATE", payload, "DRY_RUN", 200,
                 "Dry-run — no Jira issue created", None, True)
        update_alert_jira_status(session, alert_id, "SKIPPED")
        return

    # Live mode — attempt MCP call
    try:
        # MCP tool call would go here:
        # result = mcp.call("jira", "create_issue", payload)
        # For now, raise to indicate MCP not configured
        raise NotImplementedError(
            "Jira MCP not configured. Run: cortex mcp add jira"
        )
    except Exception as e:
        error_msg = str(e)
        print(f"[FAIL] Alert {alert_id}: {error_msg}")
        log_sync(session, alert_id, "CREATE", payload, "FAILED", 0, error_msg, None, False)
        update_alert_jira_status(session, alert_id, "FAILED", error_msg=error_msg)


def main():
    print(f"=== SCO Jira Alert Handler ===")
    print(f"Mode: {'DRY-RUN' if DRY_RUN else 'LIVE'}")
    print(f"Project: {PROJECT_KEY}")
    print(f"Max alerts: {MAX_ALERTS_PER_RUN}")
    print(f"Min severity: {MIN_SEVERITY}")
    print()

    session = get_session()
    alerts = fetch_pending_alerts(session)
    print(f"Found {len(alerts)} pending alerts")

    for alert in alerts:
        payload = build_jira_payload(alert)
        sync_alert_to_jira(session, alert, payload)

    print(f"\nDone. Processed {len(alerts)} alerts.")


if __name__ == "__main__":
    import sys
    if "--live" in sys.argv:
        DRY_RUN = False
    main()
